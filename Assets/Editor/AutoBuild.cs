#if UNITY_EDITOR
using System;
using System.Collections;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.SceneManagement;

public static class AutoBuild
{
    private const string Tag = "[AutoBuild] ";
    private const string ScenePath = "Assets/Scenes/AutoGeneratedGame.unity";
    private const string OutputRelativePath = "build/Android/VRGame.apk";
    private const int StepCount = 8;

    private static int currentStep;

    public static void BuildAndroid()
    {
        bool succeeded = false;

        try
        {
            succeeded = Run();
        }
        catch (Exception exception)
        {
            Debug.LogError(Tag + "Unhandled exception: " + exception);
        }

        if (succeeded)
        {
            Debug.Log(Tag + "FINISHED: build succeeded.");
        }
        else
        {
            Debug.LogError(Tag + "FINISHED: build FAILED. Read the log above for the first [AutoBuild] error.");
        }

        if (Application.isBatchMode)
        {
            EditorApplication.Exit(succeeded ? 0 : 1);
        }
    }

    private static bool Run()
    {
        currentStep = 0;
        Debug.Log(Tag + "Unity " + Application.unityVersion + ", batch mode: " + Application.isBatchMode + ", project: " + Path.GetFullPath(Path.Combine(Application.dataPath, "..")));

        Step("Making sure the active build target is Android");
        if (!EnsureAndroidTarget())
        {
            return false;
        }

        Step("Creating a new scene");
        Scene scene = EditorSceneManager.NewScene(NewSceneSetup.DefaultGameObjects, NewSceneMode.Single);
        Debug.Log(Tag + "New scene created with " + scene.rootCount + " default objects.");

        Step("Building rig, floor, lighting and game objects");
        if (!BuildSceneContents(scene))
        {
            return false;
        }

        Step("Checking that script references are wired");
        ValidateWiring();

        Step("Saving the scene to " + ScenePath);
        if (!SaveScene(scene))
        {
            return false;
        }

        Step("Setting the scene list in Build Settings");
        EditorBuildSettings.scenes = new[] { new EditorBuildSettingsScene(ScenePath, true) };
        Debug.Log(Tag + "EditorBuildSettings.scenes now contains only " + ScenePath);

        Step("Checking OpenXR and configuring Android player settings");
        EnsureOpenXR();
        ConfigureAndroidPlayer();

        Step("Building the APK");
        return BuildApk();
    }

    private static void Step(string message)
    {
        currentStep++;
        Debug.Log(Tag + "Step " + currentStep + "/" + StepCount + ": " + message);
    }

    private static bool EnsureAndroidTarget()
    {
        if (EditorUserBuildSettings.activeBuildTarget == BuildTarget.Android)
        {
            Debug.Log(Tag + "Active build target is already Android.");
            return true;
        }

        Debug.LogWarning(Tag + "Active build target is " + EditorUserBuildSettings.activeBuildTarget + ". Switching to Android. In GameCI set targetPlatform: Android to skip this.");
        bool switched = EditorUserBuildSettings.SwitchActiveBuildTarget(BuildTargetGroup.Android, BuildTarget.Android);
        if (!switched || EditorUserBuildSettings.activeBuildTarget != BuildTarget.Android)
        {
            Debug.LogError(Tag + "Could not switch to Android. Make sure the Unity image has the Android module (unityci/editor ...-android-...).");
            return false;
        }

        return true;
    }

    private static bool BuildSceneContents(Scene scene)
    {
        GameObject[] roots = scene.GetRootGameObjects();
        Light defaultLight = null;
        for (int i = 0; i < roots.Length; i++)
        {
            if (roots[i].GetComponent<Camera>() != null)
            {
                Debug.Log(Tag + "Removing default camera '" + roots[i].name + "' because the VR rig brings its own camera and audio listener.");
                UnityEngine.Object.DestroyImmediate(roots[i]);
                continue;
            }

            Light light = roots[i].GetComponent<Light>();
            if (light != null && light.type == LightType.Directional)
            {
                defaultLight = light;
            }
        }

        if (defaultLight != null)
        {
            defaultLight.intensity = 1.1f;
            defaultLight.color = new Color(1f, 0.96f, 0.9f);
            defaultLight.transform.rotation = Quaternion.Euler(50f, -30f, 0f);
            Debug.Log(Tag + "Configured the default directional light.");
        }

        string[] templateRigs = AssetDatabase.FindAssets("OVRCameraRig t:Prefab");
        if (templateRigs.Length > 0)
        {
            Debug.Log(Tag + "Found template rig prefab " + AssetDatabase.GUIDToAssetPath(templateRigs[0]) + " but it is not used. The game's own rig (XRPoseDriver + ArmLocomotion) reads head and controllers straight from OpenXR and must be the only rig.");
        }
        else
        {
            Debug.Log(Tag + "No template OVRCameraRig prefab found. Building the game's own rig.");
        }

        LocomotionEditorTools.BuildSceneContents(defaultLight == null);

        XRPoseDriver poseDriver = UnityEngine.Object.FindFirstObjectByType<XRPoseDriver>();
        ArmLocomotion locomotion = UnityEngine.Object.FindFirstObjectByType<ArmLocomotion>();
        Camera[] cameras = UnityEngine.Object.FindObjectsByType<Camera>(FindObjectsSortMode.None);
        AudioListener[] listeners = UnityEngine.Object.FindObjectsByType<AudioListener>(FindObjectsSortMode.None);

        if (poseDriver == null || locomotion == null)
        {
            Debug.LogError(Tag + "Player rig missing after scene build (XRPoseDriver: " + (poseDriver != null) + ", ArmLocomotion: " + (locomotion != null) + ").");
            return false;
        }

        if (cameras.Length != 1 || listeners.Length != 1)
        {
            Debug.LogError(Tag + "Expected exactly 1 camera and 1 audio listener, found " + cameras.Length + " and " + listeners.Length + ".");
            return false;
        }

        Debug.Log(Tag + "Rig OK: head camera '" + cameras[0].name + "', left/right tracked anchors and solved hands wired.");

        MonkeAvatar[] avatars = UnityEngine.Object.FindObjectsByType<MonkeAvatar>(FindObjectsSortMode.None);
        if (avatars.Length == 1)
        {
            Debug.Log(Tag + "Monke avatar attached: arms follow the solved hands and fingers curl from trigger, grip and thumb.");
        }
        else
        {
            Debug.LogWarning(Tag + "No monke avatar in the scene, so the player uses plain sphere hands. Check that Assets/Models/Player/monke.glb imported (glTFast package).");
        }
        Debug.Log(Tag + "Mining content: rocks " + UnityEngine.Object.FindObjectsByType<MineableRock>(FindObjectsSortMode.None).Length + ", pickaxes " + UnityEngine.Object.FindObjectsByType<Pickaxe>(FindObjectsSortMode.None).Length + ", grab hands " + UnityEngine.Object.FindObjectsByType<GrabHand>(FindObjectsSortMode.None).Length + ".");

        if (UnityEngine.Object.FindObjectsByType<MineableRock>(FindObjectsSortMode.None).Length == 0)
        {
            Debug.LogWarning(Tag + "No rocks were created. Add the glTFast package (com.unity.cloud.gltfast) to Packages/manifest.json so the .glb models import.");
        }

        return true;
    }

    private static void ValidateWiring()
    {
        int missing = 0;
        missing += ReportNullReferences<XRPoseDriver>();
        missing += ReportNullReferences<ArmLocomotion>();
        missing += ReportNullReferences<GrabHand>();
        missing += ReportNullReferences<MonkeAvatar>();
        missing += ReportNullReferences<Pickaxe>();
        missing += ReportNullReferences<MineableRock>();

        if (missing == 0)
        {
            Debug.Log(Tag + "All checked script references are assigned.");
        }
        else
        {
            Debug.LogWarning(Tag + missing + " serialized reference(s) are empty. Some may be optional, check the lines above.");
        }
    }

    private static int ReportNullReferences<T>() where T : Component
    {
        int missing = 0;
        T[] components = UnityEngine.Object.FindObjectsByType<T>(FindObjectsSortMode.None);

        for (int i = 0; i < components.Length; i++)
        {
            SerializedObject serialized = new SerializedObject(components[i]);
            SerializedProperty iterator = serialized.GetIterator();
            bool enter = true;
            while (iterator.NextVisible(enter))
            {
                enter = false;
                if (iterator.name == "m_Script" || iterator.propertyType != SerializedPropertyType.ObjectReference)
                {
                    continue;
                }

                if (iterator.objectReferenceValue == null)
                {
                    missing++;
                    Debug.LogWarning(Tag + typeof(T).Name + " on '" + components[i].gameObject.name + "' has an empty reference: " + iterator.displayName);
                }
            }
        }

        return missing;
    }

    private static bool SaveScene(Scene scene)
    {
        if (!AssetDatabase.IsValidFolder("Assets/Scenes"))
        {
            AssetDatabase.CreateFolder("Assets", "Scenes");
        }

        bool saved = EditorSceneManager.SaveScene(scene, ScenePath);
        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();

        if (!saved || !File.Exists(ScenePath))
        {
            Debug.LogError(Tag + "Scene was not saved to " + ScenePath);
            return false;
        }

        Debug.Log(Tag + "Scene saved: " + ScenePath);
        return true;
    }

    private static Type FindType(string fullName)
    {
        Assembly[] assemblies = AppDomain.CurrentDomain.GetAssemblies();
        for (int i = 0; i < assemblies.Length; i++)
        {
            Type type = assemblies[i].GetType(fullName, false);
            if (type != null)
            {
                return type;
            }
        }

        return null;
    }

    private static void EnsureOpenXR()
    {
        try
        {
            Type perTarget = FindType("UnityEditor.XR.Management.XRGeneralSettingsPerBuildTarget");
            Type store = FindType("UnityEditor.XR.Management.Metadata.XRPackageMetadataStore");

            if (perTarget == null || store == null)
            {
                Debug.LogWarning(Tag + "XR Plug-in Management is not in this project. Head tracking will not work in the APK.");
                return;
            }

            object general = perTarget.GetMethod("XRGeneralSettingsForBuildTarget", BindingFlags.Public | BindingFlags.Static)
                .Invoke(null, new object[] { BuildTargetGroup.Android });

            if (general == null)
            {
                Debug.LogError(Tag + "No XR General Settings for Android. Open Project Settings > XR Plug-in Management > Android once in the template and commit the result.");
                return;
            }

            object manager = general.GetType().GetProperty("Manager").GetValue(general);
            if (manager == null)
            {
                Debug.LogError(Tag + "XR Manager Settings for Android are missing. Commit the template's XR settings assets.");
                return;
            }

            bool hasOpenXR = false;
            IEnumerable loaders = manager.GetType().GetProperty("activeLoaders").GetValue(manager) as IEnumerable;
            if (loaders != null)
            {
                foreach (object loader in loaders)
                {
                    Debug.Log(Tag + "Active Android XR loader: " + loader.GetType().Name);
                    if (loader.GetType().Name.Contains("OpenXR"))
                    {
                        hasOpenXR = true;
                    }
                }
            }

            if (!hasOpenXR)
            {
                MethodInfo assign = store.GetMethod("AssignLoader", BindingFlags.Public | BindingFlags.Static);
                object result = assign.Invoke(null, new object[] { manager, "UnityEngine.XR.OpenXR.OpenXRLoader", BuildTargetGroup.Android });
                Debug.Log(Tag + "OpenXR loader was not enabled for Android. AssignLoader returned " + result);
            }

            PropertyInfo initOnStart = general.GetType().GetProperty("InitManagerOnStart");
            if (initOnStart != null)
            {
                initOnStart.SetValue(general, true);
            }

            EditorUtility.SetDirty(general as UnityEngine.Object);
            EditorUtility.SetDirty(manager as UnityEngine.Object);
            EnableOpenXRFeature("UnityEngine.XR.OpenXR.Features.Interactions.OculusTouchControllerProfile");
            EnableOpenXRFeature("UnityEngine.XR.OpenXR.Features.MetaQuestSupport.MetaQuestFeature");
            AssetDatabase.SaveAssets();
        }
        catch (Exception exception)
        {
            Debug.LogWarning(Tag + "OpenXR check could not finish (" + exception.GetType().Name + ": " + exception.Message + "). The build continues, but confirm OpenXR, the Oculus Touch profile and Meta Quest Support are enabled in the template.");
        }
    }

    private static void EnableOpenXRFeature(string featureTypeName)
    {
        Type settingsType = FindType("UnityEngine.XR.OpenXR.OpenXRSettings");
        Type featureType = FindType(featureTypeName);

        if (settingsType == null || featureType == null)
        {
            Debug.LogWarning(Tag + "OpenXR feature type not found: " + featureTypeName);
            return;
        }

        MethodInfo getSettings = settingsType.GetMethod("GetSettingsForBuildTargetGroup", BindingFlags.Public | BindingFlags.Static);
        if (getSettings == null)
        {
            Debug.LogWarning(Tag + "Could not read OpenXR settings for Android.");
            return;
        }

        object settings = getSettings.Invoke(null, new object[] { BuildTargetGroup.Android });
        if (settings == null)
        {
            Debug.LogWarning(Tag + "OpenXR settings for Android do not exist yet.");
            return;
        }

        MethodInfo getFeature = settingsType.GetMethod("GetFeature", new[] { typeof(Type) });
        object feature = getFeature != null ? getFeature.Invoke(settings, new object[] { featureType }) : null;
        if (feature == null)
        {
            Debug.LogWarning(Tag + "OpenXR feature not found in settings: " + featureType.Name);
            return;
        }

        PropertyInfo enabled = feature.GetType().GetProperty("enabled");
        if (enabled != null && !(bool)enabled.GetValue(feature))
        {
            enabled.SetValue(feature, true);
            EditorUtility.SetDirty(feature as UnityEngine.Object);
            Debug.Log(Tag + "Enabled OpenXR feature " + featureType.Name);
        }
        else
        {
            Debug.Log(Tag + "OpenXR feature already enabled: " + featureType.Name);
        }
    }

    private static void ConfigureAndroidPlayer()
    {
        PlayerSettings.productName = "VRGame";
        PlayerSettings.companyName = "RIPPED";
        PlayerSettings.SetApplicationIdentifier(NamedBuildTarget.Android, "com.ripped.vrgame");
        PlayerSettings.SetScriptingBackend(NamedBuildTarget.Android, ScriptingImplementation.IL2CPP);
        PlayerSettings.Android.targetArchitectures = AndroidArchitecture.ARM64;
        PlayerSettings.Android.minSdkVersion = AndroidSdkVersions.AndroidApiLevel29;
        PlayerSettings.colorSpace = ColorSpace.Linear;
        PlayerSettings.SetUseDefaultGraphicsAPIs(BuildTarget.Android, false);
        PlayerSettings.SetGraphicsAPIs(BuildTarget.Android, new[] { GraphicsDeviceType.Vulkan, GraphicsDeviceType.OpenGLES3 });
        EditorUserBuildSettings.androidBuildSystem = AndroidBuildSystem.Gradle;
        EditorUserBuildSettings.buildAppBundle = false;
        EditorUserBuildSettings.development = false;

        Debug.Log(Tag + "Android settings: target Android, IL2CPP, ARM64, min API 29, Vulkan then GLES3, APK (not AAB).");
    }

    private static bool BuildApk()
    {
        string projectRoot = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
        string outputPath = Path.Combine(projectRoot, OutputRelativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(outputPath));
        if (File.Exists(outputPath))
        {
            File.Delete(outputPath);
        }

        BuildPlayerOptions options = new BuildPlayerOptions
        {
            scenes = new[] { ScenePath },
            locationPathName = outputPath,
            target = BuildTarget.Android,
            targetGroup = BuildTargetGroup.Android,
            options = BuildOptions.None
        };

        Debug.Log(Tag + "BuildPipeline.BuildPlayer starting. Output: " + outputPath);
        BuildReport report = BuildPipeline.BuildPlayer(options);
        BuildSummary summary = report.summary;

        Debug.Log(Tag + "Build result: " + summary.result + ", errors: " + summary.totalErrors + ", warnings: " + summary.totalWarnings + ", time: " + summary.totalTime);

        if (summary.result != BuildResult.Succeeded)
        {
            foreach (BuildStep buildStep in report.steps)
            {
                foreach (BuildStepMessage message in buildStep.messages)
                {
                    if (message.type == LogType.Error || message.type == LogType.Exception)
                    {
                        Debug.LogError(Tag + "Build error in step '" + buildStep.name + "': " + message.content);
                    }
                }
            }

            return false;
        }

        if (!File.Exists(outputPath))
        {
            Debug.LogError(Tag + "BuildPlayer reported success but " + outputPath + " does not exist.");
            return false;
        }

        Debug.Log(Tag + "APK written: " + outputPath + " (" + (new FileInfo(outputPath).Length / 1048576f).ToString("0.0") + " MB)");
        return true;
    }
}
